def P(t, s="p"): return Paragraph(t, st[s])
def bl(items): return [Paragraph(t, st["li"], bulletText="•") for t in items]
def b(x): return "<b>%s</b>" % x

def table(head, rows, widths):
    data = [[Paragraph(h, st["th"]) for h in head]]
    for r in rows: data.append([Paragraph(str(c), st["td"]) for c in r])
    t = Table(data, colWidths=widths, repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND",(0,0),(-1,0),ACC), ("VALIGN",(0,0),(-1,-1),"TOP"),
        ("GRID",(0,0),(-1,-1),0.4,RULE),
        ("ROWBACKGROUNDS",(0,1),(-1,-1),[colors.white,BGW]),
        ("LEFTPADDING",(0,0),(-1,-1),5),("RIGHTPADDING",(0,0),(-1,-1),5),
        ("TOPPADDING",(0,0),(-1,-1),4),("BOTTOMPADDING",(0,0),(-1,-1),4)]))
    return t

def box(paras, bg=BG, bar=ACC):
    inner = Table([[p] for p in paras], colWidths=[158*mm])
    inner.setStyle(TableStyle([("LEFTPADDING",(0,0),(-1,-1),0),("RIGHTPADDING",(0,0),(-1,-1),0),
                               ("TOPPADDING",(0,0),(-1,-1),1.5),("BOTTOMPADDING",(0,0),(-1,-1),1.5)]))
    t = Table([[inner]], colWidths=[166*mm])
    t.setStyle(TableStyle([("BACKGROUND",(0,0),(-1,-1),bg),("LINEBEFORE",(0,0),(0,-1),2.2,bar),
                           ("LEFTPADDING",(0,0),(-1,-1),8),("RIGHTPADDING",(0,0),(-1,-1),6),
                           ("TOPPADDING",(0,0),(-1,-1),6),("BOTTOMPADDING",(0,0),(-1,-1),6)]))
    return t

